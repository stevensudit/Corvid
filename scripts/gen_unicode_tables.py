def ranges_for(major: str) -> list[tuple[int, int]]:
    """Collect inclusive ranges of code points whose category starts with major."""
    out: list[tuple[int, int]] = []
    start = None
    for cp in range(MAX_CP + 2):
        hit = cp <= MAX_CP and unicodedata.category(chr(cp)).startswith(major)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def emit_table(name: str, doc: str, ranges: list[tuple[int, int]]) -> str:
    lines = [f"// {doc}", f"inline constexpr std::array<codepoint_range, {len(ranges)}> {name}{{{{"]
    for first, last in ranges:
        lines.append(f"    {{0x{first:04X}, 0x{last:04X}}},")
    lines.append("}};")
    return "\n".join(lines) + "\n"


def main() -> None:
    letters = ranges_for("L")
    numbers = ranges_for("N")
    version = unicodedata.unidata_version
    body = f"""{LICENSE}#pragma once
#include <array>

// Generated by scripts/gen_unicode_tables.py from Python's unicodedata
// (Unicode {version}). Do not edit by hand; rerun the script.
//
// Each table is a sorted list of disjoint, inclusive code point ranges for
// one Unicode class. The classifier that searches them is in unicode.h.

namespace corvid::strings::unicode {{

// Inclusive range of code points.
struct codepoint_range {{
  char32_t first;
  char32_t last;
}};

{emit_table("letter_ranges", "General category L (letter): Lu, Ll, Lt, Lm, Lo.", letters)}
{emit_table("number_ranges", "General category N (number): Nd, Nl, No.", numbers)}
{emit_table("white_space_ranges", "White_Space property (PropList.txt), which is what a regex backslash-s matches.", WHITE_SPACE)}
}} // namespace corvid::strings::unicode
"""
    OUT.write_text(body, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: Unicode {version}, "
          f"{len(letters)} letter, {len(numbers)} number, "
          f"{len(WHITE_SPACE)} white_space ranges", file=sys.stderr)


if __name__ == "__main__":
    main()
