#!/usr/bin/env python3
"""Generate corvid/strings/unicode_tables.h from Python's Unicode database.

The tables answer, for any code point, which of a small set of Unicode
properties it has: the general categories Letter (L) and Number (N), and the
White_Space property. Python's unicodedata module carries the general
category for every code point, so those come from it with no download.
White_Space is a property, not a category, and unicodedata does not expose
it; the list is short and stable, so it is spelled out here from PropList.txt.

The layout is a two-stage table. A code point's high bits select a page
through an index, and its low bits select a byte within that page; the byte
is a bitmap of the properties. Identical pages are shared, which is what
makes the structure small: most 256-code-point pages are entirely letters
or entirely unassigned, and the whole space collapses to a little over a
hundred distinct pages. The lookup is two loads and no branches.

Run from anywhere; the output path is fixed relative to the repository root.
The output is passed through clang-format when it is on the PATH, so the
committed file is stable under ./format_all.sh.
"""

import shutil
import subprocess
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "corvid/strings/unicode_tables.h"
MAX_CP = 0x10FFFF
PAGE_SHIFT = 8
PAGE_SIZE = 1 << PAGE_SHIFT

# Property bits. The classifier in unicode.h names these through the
# constants emitted below, never by value.
LETTER = 0x01
NUMBER = 0x02
WHITE_SPACE = 0x04

# White_Space property, Unicode PropList.txt. Unchanged since Unicode 6.
WHITE_SPACE_RANGES = [
    (0x0009, 0x000D),
    (0x0020, 0x0020),
    (0x0085, 0x0085),
    (0x00A0, 0x00A0),
    (0x1680, 0x1680),
    (0x2000, 0x200A),
    (0x2028, 0x2029),
    (0x202F, 0x202F),
    (0x205F, 0x205F),
    (0x3000, 0x3000),
]

