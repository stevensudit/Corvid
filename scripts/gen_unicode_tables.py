def properties() -> bytes:
    """Return the property bitmap for every code point, indexed by code point."""
    out = bytearray(MAX_CP + 1)
    for cp in range(MAX_CP + 1):
        major = unicodedata.category(chr(cp))[0]
        if major == "L":
            out[cp] |= LETTER
        elif major == "N":
            out[cp] |= NUMBER
    for first, last in WHITE_SPACE_RANGES:
        for cp in range(first, last + 1):
            out[cp] |= WHITE_SPACE
    return bytes(out)


def paginate(values: bytes) -> tuple[list[bytes], list[int]]:
    """Split values into pages, sharing identical ones; return pages and index."""
    pages: dict[bytes, int] = {}
    index: list[int] = []
    for start in range(0, len(values), PAGE_SIZE):
        page = values[start : start + PAGE_SIZE]
        index.append(pages.setdefault(page, len(pages)))
    return list(pages), index


def emit_values(values: bytes | list[int]) -> str:
    # No trailing comma, so clang-format packs the elements to the column
    # limit instead of putting each on its own line.
    return ", ".join(str(v) for v in values)


def main() -> None:
    pages, index = paginate(properties())
    if len(pages) > 256:
        sys.exit(f"{len(pages)} pages no longer fit a one-byte index")
    version = unicodedata.unidata_version
    page_lines = ",\n".join(f"    {{{{{emit_values(page)}}}}}" for page in pages)
    body = f"""{LICENSE}#pragma once
#include <array>
#include <cstddef>
#include <cstdint>

// Generated by scripts/gen_unicode_tables.py from Python's unicodedata
// (Unicode {version}). Do not edit by hand; rerun the script.
//
// A two-stage property table. `property_index[cp >> page_shift]` selects a
// page, and the low `page_shift` bits of `cp` select a byte within it: a
// bitmap of the properties below. Identical pages are stored once.

namespace corvid::strings::unicode {{

inline constexpr char32_t max_code_point = 0x{MAX_CP:X};
inline constexpr size_t page_shift = {PAGE_SHIFT};

// General category L: Lu, Ll, Lt, Lm, Lo.
inline constexpr uint8_t letter_bit = 0x{LETTER:02X};

// General category N: Nd, Nl, No.
inline constexpr uint8_t number_bit = 0x{NUMBER:02X};

// The White_Space property (PropList.txt), which is what a regex
// backslash-s matches.
inline constexpr uint8_t white_space_bit = 0x{WHITE_SPACE:02X};

// The distinct pages, each covering {PAGE_SIZE} consecutive code points.
inline constexpr std::array<std::array<uint8_t, {PAGE_SIZE}>, {len(pages)}>
    property_pages{{{{
{page_lines}}}}};

// The page for each {PAGE_SIZE}-code-point block of the code space.
inline constexpr std::array<uint8_t, {len(index)}> property_index{{
    {emit_values(index)}}};

}} // namespace corvid::strings::unicode
"""
    OUT.write_text(body, encoding="utf-8")
    if clang_format := shutil.which("clang-format"):
        subprocess.run([clang_format, "-i", str(OUT)], check=True)
    print(f"wrote {OUT.relative_to(ROOT)}: Unicode {version}, "
          f"{len(index)} index entries, {len(pages)} distinct pages",
          file=sys.stderr)


if __name__ == "__main__":
    main()
