#!/usr/bin/env python3
"""Generate corvid/strings/unicode_tables.h from Python's Unicode database.

The tokenizer pre-split rules (GPT-2's and every later one) classify code
points by the Unicode general categories Letter (L) and Number (N) and by
the White_Space property. Python's unicodedata module carries the general
category for every code point, so the tables come from it with no download.
White_Space is a property, not a category, and unicodedata does not expose
it; the list is short and stable, so it is spelled out here from PropList.txt.

The output is data only: sorted, disjoint, inclusive code point ranges. The
classifier that searches them is hand-written in the UTF-8 side quest.

Run from anywhere; the output path is fixed relative to the repository root.
"""

import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "corvid/strings/unicode_tables.h"
MAX_CP = 0x10FFFF

# White_Space property, Unicode PropList.txt. Unchanged since Unicode 6.
WHITE_SPACE = [
    (0x0009, 0x000D),
    (0x0020, 0x0020),
    (0x0085, 0x0085),
    (0x00A0, 0x00A0),
    (0x1680, 0x1680),
    (0x2000, 0x200A),
    (0x2028, 0x2029),
    (0x202F, 0x202F),
    (0x205F, 0x205F),
    (0x3000, 0x3000),
]

